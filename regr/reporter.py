    def _get_javascript(self) -> str:
        """Get JavaScript for the report."""
        return """
        function toggleRuns(caseId) {
            const runsTable = document.getElementById('runs-' + caseId);
            const toggle = document.getElementById('toggle-' + caseId);

            if (runsTable.classList.contains('show')) {
                runsTable.classList.remove('show');
                toggle.textContent = 'Show Details';
            } else {
                runsTable.classList.add('show');
                toggle.textContent = 'Hide Details';
            }
        }
        """

    def _build_runtime_section(self) -> str:
        """Build runtime status section HTML."""
        snapshot = self.runtime_snapshot or {}
        stats = snapshot.get('stats') or {}
        running_cases = snapshot.get('running_cases') or []
        elapsed = snapshot.get('elapsed', '00:00:00')
        last_updated = snapshot.get('last_updated', 'N/A')
        stopped = snapshot.get('stopped', False)
        state = 'Stopped' if stopped else 'Running'

        runtime_cards = f"""
        <div class=\"runtime-grid\">
            <div class=\"stat-card total\">
                <h3>Total</h3>
                <div class=\"value\">{stats.get('total', 0)}</div>
            </div>
            <div class=\"stat-card pass\">
                <h3>Completed</h3>
                <div class=\"value\">{stats.get('completed', 0)}</div>
            </div>
            <div class=\"stat-card total\">
                <h3>Running</h3>
                <div class=\"value\">{stats.get('running', 0)}</div>
            </div>
            <div class=\"stat-card warn\">
                <h3>Pending</h3>
                <div class=\"value\">{stats.get('pending', 0)}</div>
            </div>
            <div class=\"stat-card fail\">
                <h3>Failed</h3>
                <div class=\"value\">{stats.get('failed', 0)}</div>
            </div>
        </div>
        """

        running_table = self._build_running_cases_table(running_cases)

        return f"""
        <div class=\"runtime-panel\">
            <div class=\"runtime-meta\">
                <p><strong>Status:</strong> {html.escape(state)}</p>
                <p><strong>Elapsed:</strong> {html.escape(str(elapsed))}</p>
                <p><strong>Last Updated:</strong> {html.escape(str(last_updated))}</p>
                <p><strong>Auto Refresh:</strong> 30s</p>
            </div>
            {runtime_cards}
            <h3>Running Cases</h3>
            {running_table}
        </div>
        """

    def _build_running_cases_table(self, running_cases: list) -> str:
        """Build running cases table HTML."""
        if not running_cases:
            return '<p class="empty-note">No running simulations.</p>'

        rows = []
        for case in running_cases:
            rows.append(f"""
                <tr>
                    <td>{html.escape(str(case.get('tc', '')))}</td>
                    <td>{html.escape(str(case.get('mode', '')))}</td>
                    <td>{html.escape(str(case.get('seed', '')))}</td>
                    <td>{html.escape(str(case.get('start_time', '')))}</td>
                    <td>{html.escape(str(case.get('elapsed', '')))}</td>
                    <td class=\"command-cell\">{html.escape(str(case.get('command', '')))}</td>
                </tr>
            """)

        return f"""
        <table>
            <thead>
                <tr>
                    <th>Test Case</th>
                    <th>Mode</th>
                    <th>Seed</th>
                    <th>Start Time</th>
                    <th>Elapsed</th>
                    <th>Command</th>
                </tr>
            </thead>
            <tbody>
                {''.join(rows)}
            </tbody>
        </table>
        """

    def _build_stats_section(self, stats: dict) -> str:
        """Build statistics section HTML."""
        duration_str = self._format_duration(stats['total_duration'])

        return f"""
        <div class=\"stat-card total\">
            <h3>Total Cases</h3>
            <div class=\"value\">{stats['total_cases']}</div>
            <div class=\"rate\">{stats['passed_cases']} passed / {stats['failed_cases']} failed</div>
        </div>
        <div class=\"stat-card pass\">
            <h3>Case Pass Rate</h3>
            <div class=\"value\">{stats['case_pass_rate']:.1f}%</div>
        </div>
        <div class=\"stat-card total\">
            <h3>Total Runs</h3>
            <div class=\"value\">{stats['total_runs']}</div>
            <div class=\"rate\">{stats['passed_runs']} passed / {stats['failed_runs']} failed</div>
        </div>
        <div class=\"stat-card pass\">
            <h3>Run Pass Rate</h3>
            <div class=\"value\">{stats['run_pass_rate']:.1f}%</div>
        </div>
        <div class=\"stat-card total\">
            <h3>Total Duration</h3>
            <div class=\"value\">{html.escape(duration_str)}</div>
        </div>
        """

    def _build_cases_section(self, report_dir: str = "") -> str:
        """Build test cases section HTML."""
        if not self.results:
            return "<p>No test cases executed</p>"

        html_parts = []
        sorted_cases = sorted(self.results.items(), key=lambda x: x[0])

        for idx, (tc, case_result) in enumerate(sorted_cases):
            html_parts.append(self._build_case_item(tc, case_result, idx, report_dir))

        return "\n".join(html_parts)

    def _build_case_item(self, tc: str, case_result: CaseResult, idx: int, report_dir: str = "") -> str:
        """Build HTML for a single test case."""
        status_class = "pass" if case_result.passed else "fail"
        status_text = "PASS" if case_result.passed else "FAIL"
        runs_info = f"{case_result.pass_count}/{case_result.times} passed"

        return f"""
        <div class=\"case-item\">
            <div class=\"case-header\" onclick=\"toggleRuns('{idx}')\">
                <div class=\"case-name\">{html.escape(tc)}</div>
                <div class=\"case-info\">
                    <span class=\"case-stats\">mode={html.escape(case_result.mode)} | {html.escape(runs_info)}</span>
                    <span class=\"case-status {status_class}\">{status_text}</span>
                    <span class=\"case-toggle\" id=\"toggle-{idx}\">Show Details</span>
                </div>
            </div>
            <div class=\"runs-table\" id=\"runs-{idx}\">
                {self._build_runs_table(case_result, report_dir)}
            </div>
        </div>
        """

    def _build_runs_table(self, case_result: CaseResult, report_dir: str = "") -> str:
        """Build HTML table for runs."""
        rows = []

        for run in case_result.runs:
            status_class = "pass" if run.passed else "fail"
            status_text = "PASS" if run.passed else "FAIL"
            retry_info = f" ({run.retry_count} retries)" if run.retry_count > 0 else ""

            log_link = "-"
            if run.log_path:
                log_name = os.path.basename(run.log_path)
                log_rel_path = os.path.relpath(run.log_path, report_dir) if report_dir else run.log_path
                log_link = f'<a class="log-link" href="{html.escape(log_rel_path)}">{html.escape(log_name)}</a>'

            error_msg = run.error_message if run.error_message else "-"
            error_msg_escaped = html.escape(error_msg)

            rows.append(f"""
                <tr>
                    <td>Run {run.run_id}</td>
                    <td>{run.seed}</td>
                    <td><span class=\"run-status {status_class}\">{status_text}{html.escape(retry_info)}</span></td>
                    <td>{run.duration:.1f}s</td>
                    <td>{log_link}</td>
                    <td class=\"error-msg\" title=\"{error_msg_escaped}\">{error_msg_escaped}</td>
                </tr>
            """)

        return f"""
        <table>
            <thead>
                <tr>
                    <th>Run</th>
                    <th>Seed</th>
                    <th>Status</th>
                    <th>Duration</th>
                    <th>Log</th>
                    <th>Error</th>
                </tr>
            </thead>
            <tbody>
                {''.join(rows)}
            </tbody>
        </table>
        """

    def _format_duration(self, seconds: float) -> str:
        """Format duration in seconds to human-readable string."""
        if seconds < 60:
            return f"{seconds:.1f}s"
        if seconds < 3600:
            minutes = seconds / 60
            return f"{minutes:.1f}min"
        hours = seconds / 3600
        return f"{hours:.1f}h"

    def update_results(self, results: Dict[str, CaseResult]):
        """Update results dictionary with partial results."""
        self.results.update(results)

    def update_runtime_snapshot(self, snapshot: Optional[dict]):
        """Update runtime snapshot for real-time HTML rendering."""
        self.runtime_snapshot = snapshot or None
