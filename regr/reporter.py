"""
Reporter module for generating HTML reports.
"""

import html
import logging
import os
from typing import Dict, Optional

from .config import RegressionConfig
from .executor import CaseResult


class Reporter:
    """HTML report generator for regression results."""

    def __init__(self, config: RegressionConfig, results: Dict[str, CaseResult],
                 timestamp: str, git_hash: str = ""):
        """Initialize reporter.

        Args:
            config: Regression configuration
            results: Dictionary of case results
            timestamp: Regression timestamp
            git_hash: Git commit hash
        """
        self.config = config
        self.results = results
        self.timestamp = timestamp
        self.git_hash = git_hash
        self.runtime_snapshot: Optional[dict] = None
        self.logger = logging.getLogger("regr")

    def _calculate_stats(self) -> dict:
        """Calculate overall statistics."""
        total_cases = len(self.results)
        passed_cases = sum(1 for r in self.results.values() if r.passed)
        failed_cases = total_cases - passed_cases

        total_runs = sum(r.times for r in self.results.values())
        passed_runs = sum(r.pass_count for r in self.results.values())
        failed_runs = sum(r.fail_count for r in self.results.values())

        total_duration = sum(
            sum(run.duration for run in case.runs)
            for case in self.results.values()
        )

        return {
            'total_cases': total_cases,
            'passed_cases': passed_cases,
            'failed_cases': failed_cases,
            'case_pass_rate': (passed_cases / total_cases * 100) if total_cases > 0 else 0,
            'total_runs': total_runs,
            'passed_runs': passed_runs,
            'failed_runs': failed_runs,
            'run_pass_rate': (passed_runs / total_runs * 100) if total_runs > 0 else 0,
            'total_duration': total_duration,
        }

    def generate_html(self, output_path: str) -> bool:
        """Generate HTML report."""
        self._output_path = output_path
        stats = self._calculate_stats()
        html_content = self._build_html(stats)

        try:
            os.makedirs(os.path.dirname(output_path), exist_ok=True)
            with open(output_path, 'w', encoding='utf-8') as f:
                f.write(html_content)
            return True
        except Exception as e:
            self.logger.error("Failed to generate report: %s", e)
            return False

    def _build_html(self, stats: dict) -> str:
        """Build complete HTML report."""
        report_dir = os.path.dirname(self._output_path) if hasattr(self, '_output_path') else ""

        return f"""<!DOCTYPE html>
<html lang=\"en\">
<head>
    <meta charset=\"UTF-8\">
    <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">
    <meta http-equiv=\"refresh\" content=\"30\">
    <title>Regression Report - {html.escape(self.timestamp)}</title>
    <style>
        {self._get_css()}
    </style>
</head>
<body>
    <div class=\"container\">
        <h1>Regression Report</h1>

        <div class=\"info\">
            <p><strong>Timestamp:</strong> {html.escape(self.timestamp)}</p>
            <p><strong>Git Hash:</strong> {html.escape(self.git_hash or 'N/A')}</p>
            <p><strong>Configuration:</strong> jobs={self.config.jobs}, retry={self.config.retry}</p>
        </div>

        <h2>Runtime Status</h2>
        <div class=\"runtime-section\">
            {self._build_runtime_section()}
        </div>

        <h2>Summary</h2>
        <div class=\"stats-grid\">
            {self._build_stats_section(stats)}
        </div>

        <h2>Test Cases</h2>
        <div class=\"cases-section\">
            {self._build_cases_section(report_dir)}
        </div>

        <footer>
            <p>Generated by IC Verification Regression Script v1.0.0</p>
        </footer>
    </div>

    <script>
        {self._get_javascript()}
    </script>
</body>
</html>"""

